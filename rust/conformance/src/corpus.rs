//! The vector corpus shared with bare-ts (test 4).
//!
//! Valid vectors are candidate encodings of sampled values with their JSON form; invalid vectors
//! are truncations, trailing bytes and hand-written malformed inputs. `bare-ts/check.mjs`
//! documents the JSON format.

use crate::{
    desc::{self, Desc},
    harness::{self, Entry},
    ENTRIES,
};
use serde_json::{json, Value};

/// Sets that have bare-ts schema copies and are not built from `VBARE_EXTRA_SCHEMAS`.
pub const CORPUS_SETS: &[&str] = &["reference", "candidate", "spec", "basic"];

/// Samples per user type.
pub const SAMPLES: usize = 4;

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|byte| format!("{byte:02x}")).collect()
}

fn schema(entry: &Entry) -> String {
    format!("{}/{}", entry.id.set, entry.id.module)
}

fn find(set: &str, module: &str, name: &str) -> &'static Entry {
    ENTRIES
        .iter()
        .find(|entry| entry.id.set == set && entry.id.module == module && entry.id.name == name)
        .unwrap_or_else(|| panic!("no entry {set}/{module}::{name}"))
}

/// Builds a corpus for the user types of `sets`, deterministically.
pub fn generate(sets: &[&str]) -> Value {
    let mut vectors = Vec::new();
    let mut runner = harness::deterministic_runner();
    for entry in ENTRIES.iter() {
        if !sets.contains(&entry.id.set) || !entry.user_type || matches!(entry.desc, Desc::Void) {
            continue;
        }
        let mut produced = 0;
        let mut attempts = 0;
        while produced < SAMPLES && attempts < SAMPLES * 20 {
            attempts += 1;
            let bytes = (entry.sample)(&mut runner);
            // JavaScript quiets signaling f32 NaNs, so those values stay out of the corpus.
            let Ok(value) = desc::to_json(entry.desc, &bytes) else {
                continue;
            };
            vectors.push(json!({
                "schema": schema(entry),
                "type": entry.id.name,
                "value": value,
                "hex": hex(&bytes),
            }));
            if !bytes.is_empty() {
                vectors.push(json!({
                    "schema": schema(entry),
                    "type": entry.id.name,
                    "hex": hex(&bytes[..bytes.len() - 1]),
                    "invalid": "truncated",
                }));
            }
            let mut trailing = bytes.clone();
            trailing.push(0);
            vectors.push(json!({
                "schema": schema(entry),
                "type": entry.id.name,
                "hex": hex(&trailing),
                "invalid": "trailing byte",
            }));
            produced += 1;
        }
    }
    if sets.contains(&"reference") {
        vectors.extend(hand_written());
    }
    json!({
        "source": "Generated by `VBARE_UPDATE_CORPUS=1 cargo test -p vbare-conformance --test bare_ts`.",
        "vectors": vectors,
    })
}

/// Boundary and malformed inputs for types in `reference/all_v1`.
fn hand_written() -> Vec<Value> {
    let mut vectors = Vec::new();
    let mut valid = |name: &str, hex: &str| {
        let entry = find("reference", "all_v1", name);
        let bytes = from_hex(hex);
        let value = desc::to_json(entry.desc, &bytes)
            .unwrap_or_else(|error| panic!("{name} {hex}: {error}"));
        vectors.push(
            json!({ "schema": "reference/all_v1", "type": name, "value": value, "hex": hex }),
        );
    };
    // UTF-8 boundaries: U+10FFFF, a 4-byte emoji and an embedded NUL.
    valid("Name", "04f48fbfbf");
    valid("Name", "04f09f9880");
    valid("Name", "03610062");
    // Varint length boundaries: 1, 2, 9 and 10 bytes.
    valid("Counter", "7f");
    valid("Counter", "8001");
    valid("Counter", "ffffffffffffffff7f");
    valid("Counter", "ffffffffffffffffff01");
    valid("Flag", "01");
    valid("MaybeU8", "0105");
    valid("Dict", "02016101016202");
    let mut invalid = |name: &str, hex: &str, reason: &str| {
        vectors.push(
            json!({ "schema": "reference/all_v1", "type": name, "hex": hex, "invalid": reason }),
        );
    };
    invalid("Name", "02c080", "overlong UTF-8");
    invalid("Name", "03eda080", "UTF-8 surrogate");
    invalid("Name", "04f4908080", "above U+10FFFF");
    invalid("Name", "05616263", "length above remaining");
    invalid("Flag", "02", "bool byte 2");
    invalid("MaybeU8", "0205", "optional tag 2");
    invalid("Counter", "8000", "non-minimal varint");
    invalid(
        "Counter",
        "ffffffffffffffffff00",
        "non-minimal 10-byte varint",
    );
    invalid("Counter", "ffffffffffffffffff02", "varint above 64 bits");
    invalid("Counter", "ffffffffffffffffff8101", "11-byte varint");
    invalid("Dict", "02016101016102", "duplicate map key");
    invalid("Dict", "05016101", "count above remaining");
    invalid("Color", "03", "unknown enum value");
    invalid("Sparse", "02", "unknown enum value");
    invalid("Value", "07", "unknown union tag");
    invalid(
        "Lists",
        "ff7f",
        "count claims more elements than remaining bytes",
    );
    vectors
}

pub fn from_hex(hex: &str) -> Vec<u8> {
    (0..hex.len() / 2)
        .map(|index| u8::from_str_radix(&hex[2 * index..2 * index + 2], 16).expect("valid hex"))
        .collect()
}

/// Formats a corpus with one vector per line, which keeps diffs readable.
pub fn to_text(corpus: &Value) -> String {
    let vectors: Vec<String> = corpus["vectors"]
        .as_array()
        .map(|vectors| {
            vectors
                .iter()
                .map(|vector| format!("    {vector}"))
                .collect()
        })
        .unwrap_or_default();
    format!(
        "{{\n  \"source\": {},\n  \"vectors\": [\n{}\n  ]\n}}\n",
        corpus["source"],
        vectors.join(",\n")
    )
}

/// Checks the candidate against a corpus: valid vectors decode to their JSON value and
/// re-encode to their bytes, invalid vectors are rejected, and `decode` agrees with `view` on
/// every vector. Returns the number checked.
pub fn check_candidate(corpus: &Value) -> Result<usize, Vec<String>> {
    let mut failures = Vec::new();
    let mut checked = 0;
    let vectors = corpus["vectors"].as_array().cloned().unwrap_or_default();
    for vector in &vectors {
        let schema = vector["schema"].as_str().unwrap_or_default();
        let (set, module) = schema.split_once('/').unwrap_or((schema, ""));
        let name = vector["type"].as_str().unwrap_or_default();
        let hex_bytes = vector["hex"].as_str().unwrap_or_default();
        let label = format!("{schema}::{name} {hex_bytes}");
        let Some(entry) = ENTRIES.iter().find(|entry| {
            entry.id.set == set && entry.id.module == module && entry.id.name == name
        }) else {
            failures.push(format!("{label}: no such type"));
            continue;
        };
        let bytes = from_hex(hex_bytes);
        let result = (entry.candidate_canonical)(&bytes);
        checked += 1;
        if let Err(error) = (entry.decode_agreement)(&bytes) {
            failures.push(format!("{label}: {error}"));
        }
        if let Some(reason) = vector.get("invalid") {
            if result.is_ok() {
                failures.push(format!(
                    "{label}: candidate accepted invalid input ({reason})"
                ));
            }
            continue;
        }
        match result {
            Ok(canonical) if canonical == bytes => {}
            Ok(canonical) => failures.push(format!("{label}: re-encoded as {}", hex(&canonical))),
            Err(error) => failures.push(format!("{label}: candidate rejected: {error}")),
        }
        match desc::to_json(entry.desc, &bytes) {
            Ok(value) if value == vector["value"] => {}
            Ok(value) => failures.push(format!("{label}: decodes to {value}")),
            Err(error) => failures.push(format!("{label}: {error}")),
        }
    }
    if failures.is_empty() {
        Ok(checked)
    } else {
        Err(failures)
    }
}
